/**
  * Init USB device Library, add supported class and start the library
  * @retval None
  */
void MX_USB_DEVICE_Init(void)
{
  /* USER CODE BEGIN USB_DEVICE_Init_PreTreatment */
  /* 本工程改用 TinyUSB(见 User_File/BSP/USB/bsp_usb.c)。ST 的 USB 协议栈会和 TinyUSB
     抢占 OTG_HS，必须停用。这里直接 return 让本函数空转——它在 USER CODE 段里，
     CubeMX 重新生成代码会保留，所以无需每次再去注释 main.c 的 MX_USB_DEVICE_Init()。
     不初始化 USBD 类 -> 下面的 CDC fops 表无人引用 -> 被链接器 GC 掉，不进固件。 */
  return;
  /* USER CODE END USB_DEVICE_Init_PreTreatment */

  /* Init Device Library, add supported class and start the library. */
  if (USBD_Init(&hUsbDeviceHS, &HS_Desc, DEVICE_HS) != USBD_OK)
  {
    Error_Handler();
  }
  if (USBD_RegisterClass(&hUsbDeviceHS, &USBD_CDC) != USBD_OK)
  {
    Error_Handler();
  }
  if (USBD_CDC_RegisterInterface(&hUsbDeviceHS, &USBD_Interface_fops_HS) != USBD_OK)
  {
    Error_Handler();
  }
  if (USBD_Start(&hUsbDeviceHS) != USBD_OK)
  {
    Error_Handler();
  }

  /* USER CODE BEGIN USB_DEVICE_Init_PostTreatment */
  HAL_PWREx_EnableUSBVoltageDetector();

  /* USER CODE END USB_DEVICE_Init_PostTreatment */
}


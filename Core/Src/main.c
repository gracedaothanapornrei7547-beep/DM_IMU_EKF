/**
  * @brief  The application entry point.
  * @retval int
  */
int main(void)
{

  /* USER CODE BEGIN 1 */

  /* USER CODE END 1 */

  /* MPU Configuration--------------------------------------------------------*/
  MPU_Config();

  /* MCU Configuration--------------------------------------------------------*/

  /* Reset of all peripherals, Initializes the Flash interface and the Systick. */
  HAL_Init();

  /* USER CODE BEGIN Init */

  /* USER CODE END Init */

  /* Configure the system clock */
  SystemClock_Config();

  /* USER CODE BEGIN SysInit */

  /* USER CODE END SysInit */

  /* Initialize all configured peripherals */
  MX_GPIO_Init();
  MX_FDCAN1_Init();
  MX_FDCAN2_Init();
  MX_FDCAN3_Init();
  MX_UART7_Init();
  MX_USART1_UART_Init();
  MX_USART2_UART_Init();
  MX_USART3_UART_Init();
  MX_USART10_UART_Init();
  MX_SPI2_Init();
  MX_UART5_Init();
  MX_TIM3_Init();
  MX_TIM6_Init();
  MX_TIM7_Init();
  /* USER CODE BEGIN 2 */

  usb_init();                            /* 启动 TinyUSB CDC */
  {
    uint32_t t0 = HAL_GetTick();
    while (!usb_is_ready() && (HAL_GetTick() - t0 < 2000))
    {
      usb_task();
    }
  }
  imu_init_status = IMU_Init();          /* 上电 + 加热PWM + BMI088 + Mahony */



  /* USER CODE END 2 */

  /* Init scheduler */
  osKernelInitialize();  /* Call init function for freertos objects (in cmsis_os2.c) */
  MX_FREERTOS_Init();

  /* Start scheduler */
  osKernelStart();

  /* We should never get here as control is now taken by the scheduler */

  /* Infinite loop */
  /* USER CODE BEGIN WHILE */
  while (1)
  {
    /* USER CODE END WHILE */

    /* USER CODE BEGIN 3 */
    usb_task();                           /* TinyUSB 轮询，必须高频调用 */

    /* IMU 更新已由 TIM6 中断直接完成(500Hz)。这里只做必须在 USB 上下文里的事:
     * 按 TIM7 给出的 200Hz 节拍发送 VOFA+ 一帧(tud_cdc_write 不能进中断)。 */
    if (usb_tx_pending)                   /* TIM7: 每5ms -> 200Hz */
    {
      usb_tx_pending = 0;
      vofa_send_imu();
    }
  }

  
  /* USER CODE END 3 */
}

